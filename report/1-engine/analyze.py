def r1_samples():
    path=DATA/'r1/samples.csv'
    if not path.exists():
        return []
    with path.open(newline='',encoding='utf-8') as stream:
        reader=csv.DictReader(stream)
        if tuple(reader.fieldnames or ())!=R1_SAMPLE_COLUMNS:
            raise ValueError('R1 sample columns differ from the compact schema')
        return list(reader)


def r1_expected(index,policy):
    ids=index['expected_problem_ids']
    if set(ids)!=set(policy['problems']):
        raise ValueError('R1 problem ID datasets differ from the protocol')
    expected={}
    for dataset,count in policy['problems'].items():
        problems=[str(pid) for pid in ids[dataset]]
        if len(problems)!=count or len(set(problems))!=count:
            raise ValueError(f'R1 expected problem IDs differ for {dataset}')
        expected[dataset]={pid:set(range(policy['repeats'])) for pid in problems}
    return expected


def validate_r1_samples(index,policy):
    expected=r1_expected(index,policy)
    run_names=[index['reference']['name'],*[item['name'] for item in index['engine']]]
    wanted={(dataset,pid,sample) for dataset,problems in expected.items()
            for pid,sample_ids in problems.items() for sample in sample_ids}
    grouped={name:set() for name in run_names}
    rows=r1_samples()
    for row in rows:
        run=row['run'];dataset=row['dataset'];pid=row['problem_id']
        if run not in grouped or dataset not in expected or pid not in expected[dataset]:
            raise ValueError(f'Unexpected R1 sample: {(run,dataset,pid)}')
        key=(dataset,pid,int(row['sample_idx']))
        if key in grouped[run]:
            raise ValueError(f'Duplicate R1 sample: {(run,*key)}')
        if row['is_correct'].strip().lower() not in ('true','false','1','0','yes','no'):
            raise ValueError(f"Invalid correctness value in R1 sample: {row['is_correct']!r}")
        grouped[run].add(key)
    for run,actual in grouped.items():
        if actual!=wanted:
            raise ValueError(f'Incomplete R1 sample coverage for {run}: expected {len(wanted)}, got {len(actual)}')
    return rows,expected


def compare_r1_samples(index,rows,expected):
    """Adapt the compact table to the repository comparator's established directory API."""
    import importlib.util
    tool=ROOT.parents[1]/'script/tah/evaluation/compare_runs.py'
    if not tool.exists():
        raise ValueError('compare_runs.py is unavailable')
    sys.path.insert(0,str(tool.parent))
    try:
        spec=importlib.util.spec_from_file_location('engine_report_compare',tool)
        module=importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
    finally:
        sys.path.pop(0)
    by_run={name:{dataset:[] for dataset in expected} for name in [index['reference']['name'],*[x['name'] for x in index['engine']]]}
    for row in rows:
        by_run[row['run']][row['dataset']].append(row)
    scratch=REPO/'data/tmp/report-1-engine/checks'
    scratch.mkdir(parents=True,exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='compare-r1-',dir=scratch) as temporary:
        roots={}
        for name,datasets in by_run.items():
            root=Path(temporary)/name;roots[name]=root
            run_meta=next(item for item in index['runs'] if item['name']==name)
            for dataset,records in datasets.items():
                leaf=root/dataset;leaf.mkdir(parents=True)
                with (leaf/'detailed_results.csv').open('w',newline='',encoding='utf-8') as stream:
                    writer=csv.DictWriter(stream,fieldnames=R1_RESULT_COLUMNS,lineterminator='\n')
                    writer.writeheader()
