def run_table(policy):
    rows=[];acc={};counts={}
    available=set(R1_RUNS)
    samples=r1_samples() if available else []
    for run,label in RUNS:
        if run not in available:continue
        accuracy={};counts[run]={}
        for dataset in policy['problems']:
            data=[r for r in samples if r['run']==run and r['dataset']==dataset]
            counts[run][dataset]=(sum(r['is_correct'].strip().lower() in ('true','1','yes') for r in data),len(data))
            accuracy[dataset]=counts[run][dataset][0]/len(data)
        acc[run]=accuracy
        restarts=R1_RUNS[run].get('restarts')
        rows.append([label,fmt(100*accuracy['math500'],1),fmt(100*accuracy['gpqa'],1),'n/a' if restarts is None else str(restarts)])
    engine=[r for r,_ in RUNS if r.startswith('engine-') and r in acc]
    spread='n/a'
    if engine:
        pooled=[sum(counts[r][d][0] for r in engine)/sum(counts[r][d][1] for r in engine) for d in ('math500','gpqa')]
        rows.insert(len(engine)+1 if 'reference-seed1234' in acc else len(engine),
                    ['Engine, seeds pooled',fmt(100*pooled[0],1),fmt(100*pooled[1],1),str(sum(R1_RUNS[r]['restarts'] for r in engine))])
        spread=fmt(100*max(max(acc[r][d] for r in engine)-min(acc[r][d] for r in engine) for d in policy['problems']),1)
    text=table('accuracy_runs',['Run','MATH500 acc. (%)','GPQA acc. (%)','Restarts (host-swap overflow)'],rows)
    return dict(runs_table=text,engine_spread=spread,cap=str(policy['max_new_tokens']))


