def signed(x,digits=1):
    text=fmt(100*x,digits)
    return text if text.startswith('-') or float(text)==0 else '+'+text


def r1_runs(index,policy):
    """Check compact R1 metadata and collect the run summaries used by tables."""
    runs={}
    wanted=sum(policy['problems'].values())*policy['repeats']
    records={item['name']:item for item in index['runs']}
    declarations=[dict(index['reference'],backend='tah'),*[dict(item,backend='tah_engine') for item in index['engine']]]
    if len(records)!=len(index['runs']):
        raise ValueError('Duplicate R1 run metadata')
    for spec in declarations:
        info=records.get(spec['name'])
        if not info or info['backend']!=spec['backend'] or info['seed']!=spec['seed'] or info['samples']!=wanted:
            raise ValueError('R1 run record differs from its declaration: '+str(spec))
        if info.get('status')!='complete' or set(info.get('datasets',{}))!=set(policy['problems']):
            raise ValueError('R1 dataset status is missing or incomplete: '+spec['name'])
        for dataset,count in policy['problems'].items():
            record=info['datasets'][dataset]
            status=record['run_status']
            expected=count*policy['repeats']
            if (status.get('status')!='complete' or status.get('random_seed')!=spec['seed']
                    or status.get('expected_samples')!=expected or status.get('completed_samples')!=expected):
                raise ValueError(f"R1 status differs from the protocol in {spec['name']}/{dataset}")
        for group in info['groups']:
            found={k:group['settings'][k] for k in R1_SETTINGS}
            if group['status']!='complete' or found!=R1_SETTINGS or group['settings']['_random_seed']!=spec['seed']:
                raise ValueError(f"R1 settings differ from the protocol in {spec['name']}/{group['group']}: {found}")
        totals=info.get('engine_totals') or {}
        runs[spec['name']]=dict(backend=spec['backend'],seed=spec['seed'],samples=info['samples'],restarts=totals.get('restarts'),
                                wasted_tokens=totals.get('wasted_tokens'),generated_tokens=totals.get('generated_tokens'))
    return runs


