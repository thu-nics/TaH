#!/usr/bin/env python3
"""CPU regression for the chapter: data integrity, determinism, generated numbers, rejection paths.

    python report/2-baseline/scripts/check.py

Runs analyze.py twice and compares every generated file byte for byte, checks that the
README has no unfilled placeholder and that every table number comes from analyze.py,
runs each reproduction step as a dry run, and feeds the analysis tampered copies of the
data (hash mismatch, duplicate sample, wrong settings) plus synthetic failure cases.
"""
import ast
import copy
import hashlib
import importlib.util
import os
import re
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

sys.dont_write_bytecode = True
os.environ['CUDA_VISIBLE_DEVICES'] = ''
os.environ['PYTHONDONTWRITEBYTECODE'] = '1'
ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parents[1]
SCRATCH = REPO / 'data/tmp/report-2-baseline/checks'


def snapshot():
    files = [ROOT / 'README.md', ROOT / 'APPENDIX.md', *sorted((ROOT / 'tables').glob('*')), *sorted((ROOT / 'figures').glob('*'))]
    return {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in files if p.is_file()}


def rejects(function, error=(ValueError, AssertionError)):
    try:
        function()
    except error:
        return True
    return False


def main():
    for p in ROOT.rglob('*.py'):
        ast.parse(p.read_text())
    subprocess.run([sys.executable, str(ROOT / 'analyze.py')], check=True)
    first = snapshot()
    subprocess.run([sys.executable, str(ROOT / 'analyze.py')], check=True)
    assert first == snapshot(), 'Nondeterministic generated outputs'
    readme = (ROOT / 'README.md').read_text()
    assert '{{' not in readme
    print(f'README and tables/figures: byte-identical on consecutive runs ({len(first)} files)')

    # Every table in the template is a placeholder: no hand-typed table rows or tex.
    template = (ROOT / 'README.template.md').read_text()
    typed = [line for line in template.splitlines() if line.startswith('|') and '{{' not in line
             and any(c.isdigit() for c in re.sub(r'`[^`]*`', '', line))]
    assert not typed, f'Typed table rows: {typed}'
    for tex in (ROOT / 'tables').glob('*.tex'):
        assert tex.read_text().startswith('% Generated by analyze.py'), tex
    print('Tables: all generated by analyze.py')

    for step in (['r2', '42'], ['code_tah2', '2024'], ['curate']):
        result = subprocess.run([sys.executable, str(ROOT / 'scripts/reproduce.py'), *step, '--dry-run'], check=True,
                                capture_output=True, text=True)
        assert 'run_protocol.py' in result.stdout or 'curate_r2.py' in result.stdout
    listing = subprocess.run([sys.executable, str(ROOT / 'scripts/reproduce.py')], check=True, capture_output=True, text=True)
    assert 'No work executed' in listing.stdout
    print('Reproduction steps: listing and dry runs PASS')

    spec = importlib.util.spec_from_file_location('baseline_analysis', ROOT / 'analyze.py')
    chapter = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(chapter)
    manifest = chapter.verify()
    expected_files = {'protocol.json', 'datasets.json', 'r2/samples.csv', 'r2/runs.json',
                      'code-tah2/samples.csv', 'code-tah2/runs.json'}
    assert set(manifest['files']) == expected_files
    assert not any((ROOT / 'data').rglob('graded_solutions.jsonl.xz'))
    print(f'MANIFEST: {len(manifest["files"]) + 1} files including MANIFEST.json, SHA256 verified')

    # Failure classification on synthetic rows.
    row = dict(is_correct='false', base_status='fail', entry_point='f', raw_defined_functions='',
               graded_functions='', graded_solution_empty='false', finish_reason='eos',
               generated_tokens='100', problem_id='x/1')
    assert chapter.classify(dict(row, is_correct='true'), 8192) is None
    assert chapter.classify(dict(row, graded_functions='f'), 8192) == 'logic'
    assert chapter.classify(dict(row, graded_functions='g'), 8192) == 'naming'
    assert chapter.classify(dict(row, raw_defined_functions='g'), 8192) == 'naming'
    assert chapter.classify(dict(row, raw_defined_functions='f'), 8192) == 'no_code'
    assert chapter.classify(row, 8192) == 'no_code'
    capped = dict(row, finish_reason='length', generated_tokens='8192', graded_solution_empty='true')
    assert chapter.classify(capped, 8192) == 'capped'
    assert rejects(lambda: chapter.classify(dict(capped, generated_tokens='8000'), 8192))
    print('Failure classification: logic, naming, no-code, capped and the cap check PASS')

    # Tampered data copies must be rejected.
    original = chapter.DATA
    SCRATCH.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='check-', dir=SCRATCH) as temporary:
        data = Path(temporary) / 'data'
        shutil.copytree(original, data)
        chapter.DATA = data
        try:
            target = data / 'protocol.json'
            good = target.read_bytes()
            target.write_bytes(good.replace(b'0.575', b'0.576'))
            assert rejects(chapter.verify), 'Tampered file accepted'
            target.write_bytes(good)
            runs = chapter.read_runs()
            protocol = chapter.read('protocol.json')
            chapter.check_settings(runs, protocol)
            bad = copy.deepcopy(runs)
            bad['r2-seed1234']['groups'][0]['subruns'][0]['settings']['temperature'] = 0.7
            assert rejects(lambda: chapter.check_settings(bad, protocol)), 'Wrong temperature accepted'
            bad = copy.deepcopy(runs)
            bad['code-tah2-seed42']['groups'][1]['subruns'][0]['settings']['code_prompt'] = 'harness'
            assert rejects(lambda: chapter.check_settings(bad, protocol)), 'Wrong code prompt accepted'
            info = runs['r2-seed42']['datasets']['math500']
            name = 'r2/samples.csv'
            pristine = (data / name).read_bytes()
            table_rows = chapter.rows(name)
            first_math = next(row for row in table_rows if row['run'] == 'r2-seed42' and row['dataset'] == 'math500')
            out = chapter.io.StringIO()
            writer = chapter.csv.DictWriter(out, fieldnames=chapter.SAMPLE_COLUMNS, lineterminator='\n')
            writer.writeheader(); writer.writerows(table_rows + [first_math])
            (data / name).write_text(out.getvalue())
            assert rejects(lambda: chapter.outcomes('r2-seed42', 'math500', info)), 'Duplicate sample accepted'
            (data / name).write_bytes(pristine)
            chapter.outcomes('r2-seed42', 'math500', info)
            out = chapter.io.StringIO()
            writer = chapter.csv.DictWriter(out, fieldnames=chapter.SAMPLE_COLUMNS, lineterminator='\n')
            writer.writeheader(); writer.writerows([row for row in table_rows if row is not first_math])
            (data / name).write_text(out.getvalue())
            assert rejects(lambda: chapter.outcomes('r2-seed42', 'math500', info)), 'Missing sample accepted'
        finally:
            chapter.DATA = original
    print('Rejection: tampered file, wrong temperature, wrong code prompt, duplicate and missing sample PASS')

    size = sum(p.stat().st_size for p in ROOT.rglob('*') if p.is_file())
    assert size < 3_000_000, size
    print(f'Chapter size: {size / 1e6:.2f} MB')


if __name__ == '__main__':
    main()
